import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import net from 'node:net';
import mongoose from 'mongoose';
import { MongoClient } from 'mongodb';
import express from 'express';
import { Product } from '../src/models/Product.js';
import { Warehouse } from '../src/models/Warehouse.js';
import { Order } from '../src/models/Order.js';
import { updateOrder } from '../src/services/orderInventory.js';
import docs from '../src/routes/stockIssueRoutes.js';
import { newStockIssue } from '../src/lib/stockIssue.js';
import { importCatalog, productRow } from '../src/services/productSpreadsheet.js';

test('isolated Mongo replica set: catalog, concurrent stock documents, orders and rollback', {skip: !process.env.TEST_MONGOD, timeout: 120000}, async t => {
  const dir = await mkdtemp(join(tmpdir(),'catalog-db-'));
  const portProbe = net.createServer().listen(0,'127.0.0.1'); await once(portProbe,'listening');
  const port = (portProbe.address() as net.AddressInfo).port;
  await new Promise<void>(resolve => portProbe.close(() => resolve()));
  const db = spawn(process.env.TEST_MONGOD!, ['--dbpath',dir,'--bind_ip','127.0.0.1','--port',String(port),'--replSet','test','--logpath',join(dir,'mongo.log')], {windowsHide:true,stdio:'ignore'});
  const stopped = once(db,'exit');
  t.after(async () => { await mongoose.disconnect(); if(db.exitCode === null) db.kill(); await stopped; await rm(dir,{recursive:true,force:true,maxRetries:5}); });
  const base = 'mongodb://127.0.0.1:'+port;
  const admin = new MongoClient(base+'/?directConnection=true',{serverSelectionTimeoutMS:15000});
  try { await admin.connect(); await admin.db('admin').command({replSetInitiate:{_id:'test',members:[{_id:0,host:'127.0.0.1:'+port}]}}); } finally {await admin.close();}
  await mongoose.connect(base+'/audit?replicaSet=test');
  await Promise.all(mongoose.modelNames().map(name=>mongoose.model(name).init()));
  await importCatalog([{SKU:'QA',Tên:'Sản phẩm thử','Tồn kho':0}]);
  const p = await Product.findOne({sku:'QA'}).orFail().lean();
  await importCatalog([productRow(p)]); assert.equal(await Product.countDocuments(),1);
  const w = await Warehouse.create({name:'Kho thử'});
  const app = express(); app.use(express.json()); app.use('/docs',docs);
  const http = app.listen(0,'127.0.0.1'); await once(http,'listening'); t.after(()=>{http.closeAllConnections();http.close();});
  const url='http://127.0.0.1:'+(http.address() as net.AddressInfo).port+'/docs';
  const post = async(body:any,expected:number) => {const r=await fetch(url,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});const data=await r.json();assert.equal(r.status,expected,JSON.stringify(data));return data;};
  const stock = async()=> (await Product.findById(p._id).orFail()).stock;
  const form = (type:string,qty:number)=>({...newStockIssue('QA'),documentType:type,recipient:'QA',requestId:crypto.randomUUID(),warehouseId:String(w._id),warehouseName:w.name,items:[{name:p.name,sku:'QA',unit:'Cái',productId:String(p._id),requested:qty,quantity:qty,unitPrice:0}]});
  const receipt=form('receipt',10);await post(receipt,201);await post(receipt,200);assert.equal(await stock(),10);
  const [issued]=await Promise.all([post(form('stock-issue',3),201),post(form('stock-issue',3),201)]);assert.equal(await stock(),4);
  await post({...form('handover',3),sourceIssueId:issued._id},201);assert.equal(await stock(),4);
  await post(form('handover',1),201);assert.equal(await stock(),3);
  await post(form('stock-issue',4),409);assert.equal(await stock(),3);
  const order=await Order.create({status:'pending',warehouseId:String(w._id),items:[{id:String(p._id),quantity:2}]});
  await updateOrder(String(order._id),{status:'confirmed'});assert.equal(await stock(),1);
  await updateOrder(String(order._id),{status:'cancelled'});assert.equal(await stock(),3);
});
